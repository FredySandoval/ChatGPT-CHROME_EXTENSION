import assert from 'node:assert/strict';
import { selectMarkdownMessages, jsonToMarkdown, applyMdxFrontmatter, validateMarkdownDownload } from '../lib/markdown-export.ts';
const image = { fileId: 'file-shared', assetPointer: 'file-service://file-shared', name: 'Image.png' };
const attachment = { fileId: 'file-only', name: 'Only.txt' };
const message = (role, content, extra = {}) => ({ role, content: [content], metadata: {}, model: null, contentType: 'text', ...extra });
const chat = { conversation_id: 'chat-1', title: 'Example', messages: [message('user', 'Hello', { images: [image], attachments: [attachment] }), message('assistant', 'unused', { images: [image], rendered_markdown: '```html\n<b>literal</b>\n```\n\n| Unicode |\n|---|\n| 世界 |' })], images: [image], attachments: [attachment] };
const before = JSON.stringify(chat);
const selected = selectMarkdownMessages(chat, [1, 1, -1, 999]);
assert.equal(selected.messages.length, 1);
assert.deepEqual(selected.images, [image]);
assert.deepEqual(selected.attachments, []);
assert.equal(JSON.stringify(chat), before);
assert.deepEqual(selectMarkdownMessages(chat, [1, 0]).messages, chat.messages);
assert.deepEqual(selectMarkdownMessages(chat, []).images, []);
assert.match(jsonToMarkdown(selected, '', '', true), /^```html/);
assert.match(jsonToMarkdown(selected, '', '', true), /images\/image.png/);
assert.doesNotMatch(jsonToMarkdown(selected, '', '', true), /Only.txt/);
assert.doesNotMatch(jsonToMarkdown(selected, '', '', false), /images\//);
assert.equal(jsonToMarkdown({ messages: [message('user', 'Hi')] }, 'Custom', ''), 'Custom\n\nHi\n\n---\n\n');
assert.equal(applyMdxFrontmatter('body', 'Example', '.mdx', '---\ntitle: {{title}}\n---'), '---\ntitle: Example\n---\n\nbody');
const options = { userLabel: '', assistantLabel: '', markdownExtension: '.md', mdxFrontmatter: '', includeImages: true };
validateMarkdownDownload({ chat: selected, options });
assert.throws(() => validateMarkdownDownload({ chat: selectMarkdownMessages(chat, []), options }));
assert.throws(() => validateMarkdownDownload({ chat: { ...chat, conversation_id: '../bad' }, options }));
assert.throws(() => validateMarkdownDownload({ chat, options: { ...options, markdownExtension: '.exe' } }));
const titled = jsonToMarkdown(chat, '', '', false, true);
assert.ok(titled.startsWith('# Example\n\nHello'));
assert.equal(titled.split('# Example').length - 1, 1);
assert.ok(!jsonToMarkdown(chat, '', '', false, false).startsWith('# Example'));
assert.match(jsonToMarkdown({ ...chat, title: 'A *title*\n# injected' }, '', '', false, true), /^# A \\[*]title\\[*] \\# injected/);
assert.ok(applyMdxFrontmatter(titled, 'Example', '.mdx', '---\ntitle: {{title}}\n---').startsWith('---\ntitle: Example\n---\n\n# Example'));
assert.throws(() => validateMarkdownDownload({ chat, options: { ...options, showTitle: 'yes' } }));
console.log('Markdown export checks passed.');
